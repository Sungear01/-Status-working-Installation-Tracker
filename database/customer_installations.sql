CREATE TABLE IF NOT EXISTS customer_installations (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    customer_name VARCHAR(255) NOT NULL,
    zone VARCHAR(100) NULL,
    machine_size VARCHAR(100) NULL,
    po_sent_date DATE NULL,
    po_due_date DATE NULL,
    engineer_appointment_1 DATE NULL,
    installation_date_1 DATE NULL,
    engineer_appointment_2 DATE NULL,
    installation_date_2 DATE NULL,
    engineer_appointment_3 DATE NULL,
    installation_date_3 DATE NULL,
    due_60_date DATE NULL,
    status VARCHAR(100) NOT NULL DEFAULT 'STATUS',
    notes TEXT NULL,
    construction_notes TEXT NULL,
    work_status VARCHAR(255) NULL,
    cap_notes TEXT NULL,
    updated_by BIGINT UNSIGNED NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_installation_zone (zone),
    INDEX idx_installation_machine_size (machine_size),
    INDEX idx_installation_status (status),
    INDEX idx_installation_po_sent_date (po_sent_date),
    INDEX idx_installation_due_60_date (due_60_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
